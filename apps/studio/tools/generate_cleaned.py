"""Generate the cleaned camera frames of a run with an image model.

Each actual frame is sent with two samples of the set-up's background pattern.
The model is asked to separate the bubble from the background: remove the
heaters, electrodes and stripes and replace them with a plain surface of the
samples' tone, keeping the bubble where it is. The output is an illustration
made by a model, not a measurement, and is labelled as such in the
provenance file beside the frames.

Run with the key in the environment:
    OPENAI_API_KEY=... python apps/studio/tools/generate_cleaned.py
"""

from __future__ import annotations

import argparse
import base64
import datetime as dt
import hashlib
import io
import json
import os
import sys
from pathlib import Path

import httpx
from PIL import Image

REPO = Path(__file__).resolve().parents[3]
INPUTS = Path(__file__).resolve().parent / "inputs"
EDIT_URL = "https://api.openai.com/v1/images/edits"
DEFAULT_MODEL = "gpt-image-2.5-flare"
PROMPT = (
    "Image 1 is a microscope photograph of a single vapour bubble in a microchannel, "
    "on a chip with a busy background of metal heater lines, electrode pads and stripes. "
    "Images 2 and 3 are samples of that same background pattern and its grey tone. "
    "Separate the bubble from the background: remove every heater, electrode and "
    "stripe that is not part of the bubble, and replace the background with a plain, "
    "even surface of the same grey tone as the samples, so the background looks "
    "realistic and seamless. Keep the bubble exactly where it is in image 1 and keep "
    "its outline, its dark rim, and its shading. Do not add text, colour, lines or "
    "new objects. Photorealistic, sharp, same framing."
)


def generate(frame_png: bytes, key: str, model: str) -> bytes:
    samples = [INPUTS / "background-sample-1.png", INPUTS / "background-sample-2.png"]
    files = [("image[]", ("frame.png", frame_png, "image/png"))]
    files += [("image[]", (p.name, p.read_bytes(), "image/png")) for p in samples]
    data = {"model": model, "prompt": PROMPT, "size": "1024x1024", "n": "1"}
    response = httpx.post(
        EDIT_URL,
        headers={"Authorization": f"Bearer {key}"},
        data=data,
        files=files,
        timeout=300,
    )
    if response.status_code != 200:
        raise SystemExit(f"image model returned HTTP {response.status_code}")
    return base64.b64decode(response.json()["data"][0]["b64_json"])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", default="inert6-15-57p5-s0")
    parser.add_argument("--dataset", default="Series-1-w300")
    parser.add_argument("--frames", default="1-10")
    parser.add_argument("--force", action="store_true", help="regenerate frames that exist")
    args = parser.parse_args()
    key = os.environ.get("OPENAI_API_KEY", "").strip()
    if not key:
        sys.exit("OPENAI_API_KEY is not set in this terminal")
    model = os.environ.get("NAVIERNET_STUDIO_IMAGE_MODEL", DEFAULT_MODEL)
    low, high = (int(x) for x in args.frames.split("-"))
    out_dir = REPO / "apps" / "studio" / "cleaned" / args.run
    out_dir.mkdir(parents=True, exist_ok=True)
    raw_dir = REPO / "data" / "raw" / args.dataset
    for n in range(low, high + 1):
        target = out_dir / f"frame_{n:02d}.png"
        if target.exists() and not args.force:
            print("skip", target.name, "(exists)")
            continue
        buffer = io.BytesIO()
        Image.open(raw_dir / f"{n}.tif").convert("RGB").save(buffer, format="PNG")
        target.write_bytes(generate(buffer.getvalue(), key, model))
        print("wrote", target.relative_to(REPO), flush=True)
    provenance = {
        "kind": "illustration generated by an image model, not a measurement",
        "run": args.run,
        "model": model,
        "prompt_sha256": hashlib.sha256(PROMPT.encode()).hexdigest(),
        "inputs": sorted(p.name for p in INPUTS.iterdir()),
        "generated_at": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
    }
    (out_dir / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")


if __name__ == "__main__":
    main()
