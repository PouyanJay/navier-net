ALL: tuple[Quantity, ...] = VOLUME + DERIVED + RESIDUALS + TERMS + EDGE
BY_ID: dict[str, Quantity] = {q.id: q for q in ALL}
POINT_IDS = frozenset(q.id for q in VOLUME + DERIVED + RESIDUALS + TERMS)
EDGE_IDS = frozenset(q.id for q in EDGE)


def unknown(ids_: list[str]) -> list[str]:
    return [i for i in ids_ if i not in BY_ID]


def is_available(quantity: Quantity, scene) -> bool:
    """Whether this run can produce the quantity."""
    equations = set(scene.equation_ids)
    for need in quantity.needs:
        if need == NEED_P and "p" not in scene.fields:
            return False
        if need == NEED_T and "T" not in scene.fields:
            return False
        if need == NEED_FRONT and not scene.has_front:
            return False
        if need == NEED_FOOTPRINT and not scene.has_footprint:
            return False
        if need == NEED_SHARP_THERMAL and not scene.sharp_thermal:
            return False
        if need.startswith("equation:") and need.split(":", 1)[1] not in equations:
            return False
    return True


def unavailable(ids_: list[str], scene) -> list[str]:
    return [i for i in ids_ if i in BY_ID and not is_available(BY_ID[i], scene)]


def catalogue_for(scene) -> list[dict]:
    """Every entry with its availability and the numeric factor for this run."""
    scales = scene.scales.as_dict()
    out = []
    for q in ALL:
        record = asdict(q)
        record["available"] = is_available(q, scene)
        record["factor"] = scales.get(q.scale, 1.0) if q.scale else 1.0
        out.append(record)
    return out
