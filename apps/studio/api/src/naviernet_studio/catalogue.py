"""The quantity catalogue: every number the studio can show, declared once.

An entry says what a quantity is, in which unit it is served, which model call
produces it, whether that call needs autograd, how to read it (TeX and plain
words) and what to keep in mind. The sampler reads the same table to decide how
to evaluate, so the explanation a user sees and the computation behind it can
never drift apart.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass

KIND_VOLUME = "volume"
KIND_DERIVED = "derived"
KIND_RESIDUAL = "residual"
KIND_TERM = "term"
KIND_EDGE = "edge"
KIND_BUDGET = "budget"
KIND_GEOMETRY = "geometry"

# What a quantity needs from the run: a field head, the explicit front, the
# footprint film source, or a trained equation.
NEED_P = "field:p"
NEED_T = "field:T"
NEED_FRONT = "front"
NEED_FOOTPRINT = "footprint"
NEED_SHARP_THERMAL = "sharp_thermal"


def _eq(name: str) -> str:
    return f"equation:{name}"


@dataclass(frozen=True)
class Quantity:
    id: str
    label: str
    symbol: str
    unit: str
    kind: str
    group: str
    tex: str
    plain: str
    how: str
    scale: str  # the Scales attribute the model value is multiplied by ("" for none)
    needs_grad: bool = False
    signed: bool = False
    cmap: str = "sequential"
    needs: tuple[str, ...] = ()
    caveats: tuple[str, ...] = ()
    components: tuple[str, ...] = ()


def _q(**kw) -> Quantity:
    return Quantity(**kw)


